// ─────────────────────────────────────────────
// ノートセクション統合に伴う理解度記録のインデックス移行
//
// 理解度記録は `${categoryId}:${sectionIndex}` キーで localStorage に保存される。
// セクションを統合するとインデックスがずれて既存記録が別セクションを指してしまうため、
// 旧インデックス → 新インデックスの対応表を持ち、初回読み込み時に一度だけ変換する。
//
// 運用ルール:
//   - あるカテゴリのセクション構成を変更したら、ここに対応表を1エントリ追加し
//     NOTE_SECTION_SCHEMA_VERSION を +1 する。
//   - map[旧index] = 新index。複数の旧セクションが1つに統合される場合は同じ新indexを指す。
//   - 統合時に理解度が衝突したら「最も理解できていない方」を採用する（red > yellow > green）。
//     統合後のセクションは苦手だった内容を含むため、安全側に倒す。
// ─────────────────────────────────────────────

